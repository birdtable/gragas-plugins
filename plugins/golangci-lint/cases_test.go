var update = flag.Bool("update", false, "write testdata/cases from the plugin's answers; a person reads the diff")

// kase is one case of testdata/cases: a request, and the response the plugin gives to it. Its role is read from the
// response: an ok is a case the plugin serves, an error is one it refuses.
type kase struct {
	name, op string
	body     any
}

const linters = `{"Enabled":[{"Name":"govet"},{"Name":"errcheck"}],"Disabled":[{"Name":"revive"}]}`

func gathered(have []wire.Result, cs ...wire.Config) wire.Gathered {
	return wire.Gathered{ToolVersion: "2.15.0", Config: append([]wire.Config{}, cs...), Have: append([]wire.Result{}, have...)}
}

func settings(text string) wire.File {
	return wire.File{Path: "settings.yml", Data: wire.Bytes{Data: []byte(text)}}
}

func cases() []kase {
	run := wire.Result{Kind: wire.KindRun, Stdout: &wire.Bytes{Data: []byte(linters)}, Exit: new(int), Stderr: &wire.Bytes{Data: []byte{}}, Cut: new(bool), Files: []wire.File{}}
	pl := func(round int, g wire.Gathered) wire.PlanRequest {
		return wire.PlanRequest{Gathered: g, For: wire.ForConfig, Target: "source", Round: round}
	}
	custom := "linters:\n  settings:\n    custom:\n      mine:\n        type: module\n"
	return []kase{
		{"3-plan", "plan", pl(0, gathered(nil, cfg(".golangci.yml", "version: \"2\"\n")))},
		{"4-plan", "plan", pl(0, gathered(nil))},
		{"5-plan", "plan", pl(0, gathered(nil, cfg(".golangci.yml", custom)))},
		{"6-plan", "plan", pl(0, gathered(nil, cfg(".golangci.yml", "linters:\n  a: 1\nLinters:\n  b: 2\n")))},
		{"7-plan", "plan", pl(0, gathered(nil, cfg(".golangci.toml", "a = 1\n")))},
		{"8-plan", "plan", pl(0, gathered(nil, wire.Config{Path: ".golangci.yml"}))},
		{"9-entries", "entries", wire.EntriesRequest{Gathered: gathered([]wire.Result{run}, cfg(".golangci.yml", "linters:\n  settings:\n    Revive:\n      rules: []\n")), Target: "source"}},
		{"10-entries", "entries", wire.EntriesRequest{Gathered: gathered(nil, cfg(".golangci.yml", "linters:\n  default: standard\n  enable: [revive]\n")), Target: "source"}},
		{"12-preset", "preset", wire.PresetRequest{ToolVersion: "2.15.0", Mark: "gragas:generated", Inputs: []wire.File{settings("version: \"2\"\n\nlinters:\n  default: standard\n  enable:\n    # generated:linters:begin\n    # generated:linters:end\n")}, Entries: []wire.PresetEntry{
			{Key: "govet", Target: "source", Severity: wire.SeverityError, Value: json.RawMessage(`true`), Options: json.RawMessage(`[1]`), Rules: []string{"go.govet.1"}}}}},
		{"11-preset", "preset", wire.PresetRequest{ToolVersion: "2.15.0", Mark: "Generated by gragas from the rulebook. Regenerate it, never change it by hand.", Inputs: []wire.File{settings("version: \"2\"\nrun:\n  timeout: 10m\nlinters:\n  default: standard\n  enable:\n    # generated:linters:begin\n    # generated:linters:end\n  settings:\n    revive:\n      rules:\n        - name: exported\n")}, Entries: []wire.PresetEntry{
			{Key: "errcheck", Target: "source", Severity: wire.SeverityError, Rules: []string{"go.err.1"}},
			{Key: "gocritic", Target: "source", Severity: wire.SeverityWarning, Trial: true, Rules: []string{"go.err.2"}}}}},
		// A linter bound by several rules, in the one entry the engine sends for it: its comment
		// names all six, the ids depguard carries in gragas's committed .golangci.yml. The linter is gocritic, which the
		// recorded run has on, as C23 reads a preset back through that run and matches an entry by its key alone
		// (depguard's own case, and a key in two entries, are preset_test.go's).
		{"17-preset", "preset", wire.PresetRequest{ToolVersion: "2.15.0", Mark: "gragas:generated", Inputs: []wire.File{settings("version: \"2\"\n\nlinters:\n  default: standard\n  enable:\n    # generated:linters:begin\n    # generated:linters:end\n")}, Entries: []wire.PresetEntry{
			{Key: "gocritic", Target: "source", Severity: wire.SeverityError, Rules: []string{"tests.doubles.2", "arch.shared.7", "go.style.5", "arch.ports.11", "cli.look.1", "arch.ports.24"}},
			{Key: "errcheck", Target: "source", Severity: wire.SeverityError, Rules: []string{"go.err.1"}}}}},
		{"13-rank", "rank", wire.RankRequest{ToolVersion: "2.15.0", Pairs: []wire.Pair{
			{Key: "govet", Aspect: wire.AspectValue, Preset: json.RawMessage(`true`), Found: json.RawMessage(`false`)},
			{Key: "govet", Aspect: wire.AspectValue, Preset: json.RawMessage(`false`), Found: json.RawMessage(`true`)},
			{Key: "govet", Aspect: wire.AspectValue, Preset: json.RawMessage(`true`), Found: json.RawMessage(`true`)}}}},
	}
}

func envelope(t *testing.T, k kase) []byte {
	t.Helper()
	body, err := json.Marshal(k.body)
	if err != nil {
		t.Fatal(err)
	}
	b, err := json.MarshalIndent(wire.Request{Contract: 1, Features: []string{}, Op: k.op, Body: body}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(b, '\n')
}

// TestCases serves each request of testdata/cases and holds the plugin's answer to the response beside it.
func TestCases(t *testing.T) {
	for _, k := range cases() {
		t.Run(k.name, func(t *testing.T) {
			p := newTest(t)
			req := envelope(t, k)
			var out bytes.Buffer
			if code := plugin.ServeIO(bytes.NewReader(req), &out, p); code != 0 {
				t.Fatalf("ServeIO %d", code)
			}
			var pretty bytes.Buffer
			if err := json.Indent(&pretty, bytes.TrimSpace(out.Bytes()), "", "  "); err != nil {
				t.Fatal(err)
			}
			pretty.WriteByte('\n')
			dir := filepath.Join(bundle, "testdata", "cases", k.name)
			if *update {
				if err := os.MkdirAll(dir, 0o755); err != nil {
					t.Fatal(err)
				}
				for f, b := range map[string][]byte{"request.json": req, "response.json": pretty.Bytes()} {
					if err := os.WriteFile(filepath.Join(dir, f), b, 0o644); err != nil {
						t.Fatal(err)
					}
				}
				return
			}
			for f, b := range map[string][]byte{"request.json": req, "response.json": pretty.Bytes()} {
				want, err := os.ReadFile(filepath.Join(dir, f))
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.Equal(want, b) {
					t.Errorf("%s/%s differs:\n%s\nwant\n%s", k.name, f, b, want)
				}
			}
		})
	}
}
